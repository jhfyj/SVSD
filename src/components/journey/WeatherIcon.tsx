type SpriteName = keyof typeof SPRITES;

const LABELS: Record<SpriteName, string> = {
  clearDay: "Sunny",
  clearNight: "Clear night",
  partlyDay: "Partly cloudy",
  partlyNight: "Partly cloudy",
  cloudy: "Cloudy",
  rain: "Rain",
  snow: "Snow",
  storm: "Thunderstorm",
  fog: "Fog",
};

function spriteFor({ sky, night }: Weather): SpriteName {
  if (sky === "clear") return night ? "clearNight" : "clearDay";
  if (sky === "partly") return night ? "partlyNight" : "partlyDay";
  return sky;
}

export type WeatherSpriteProps = {
  weather: Weather;
  /** Size of one pixel in CSS px; the sprites are 16 × 16. */
  pixel?: number;
  className?: string;
};

/** One weather sprite in the current text color, swapping between its two frames. */
export function WeatherSprite({ weather, pixel = 1.5, className }: WeatherSpriteProps) {
  const name = spriteFor(weather);
  return (
    <svg
      role="img"
      aria-label={LABELS[name]}
      width={16 * pixel}
      height={16 * pixel}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      fill="currentColor"
      className={cn("sprite-play", className)}
    >
      {SPRITES[name].map((rows, f) => (
        <g key={f} className={f === 0 ? "sprite-a" : "sprite-b"}>
          {rows.flatMap((row, y) => {
            // One rect per horizontal run, as in CharacterSprite.
            const rects = [];
            for (let x = 0; x < row.length; x++) {
              if (row[x] !== "#") continue;
              let end = x;
              while (row[end + 1] === "#") end++;
              rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={end - x + 1} height={1} />);
              x = end;
            }
            return rects;
          })}
        </g>
      ))}
    </svg>
  );
}

/** The weather where you are now, refreshed every 15 minutes. Empty until it's known. */
export function WeatherIcon({ pixel = 1.5, className }: { pixel?: number; className?: string }) {
  const [weather, setWeather] = useState<Weather | null>(null);
  useEffect(() => {
    let live = true;
    const load = () => currentWeather().then((w) => live && setWeather(w));
    load();
    const id = setInterval(load, 15 * 60 * 1000);
    return () => {
      live = false;
      clearInterval(id);
    };
  }, []);
  if (!weather) return <span aria-hidden className={className} style={{ width: 16 * pixel, height: 16 * pixel }} />;
  return <WeatherSprite weather={weather} pixel={pixel} className={className} />;
}
